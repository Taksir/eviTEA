"""Build both v3 detection languages from sample-independent assets.

Inputs: TE consensus FASTA, FBte family table, host reference FASTA and its
RepeatMasker TE annotation.  The frozen G1A anchor catalogue and provenance
(the candidate universe) are regenerated by ``incumbent.anchor_census`` from
the TE library alone -- no sample, no msBWT census -- and serialized in the
historical G1A column semantics the builders consume.

    catalogue -> rebuild (terminal k=21) -> mixed-k gap fill -> finalizer
              -> final safe terminal codebook
    catalogue + final terminal codebook -> internal-21 gate
              -> internal-only safe codebook
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from ..incumbent.anchor_census import build_anchor_catalogue, load_te_family_map, parse_te_consensus
from .common import canonical_seq
from .internal import READ_LENGTH, InternalResult, build_internal21
from .terminal import (
    FinalTerminalResult,
    GapFillResult,
    RebuildResult,
    fill_underpowered,
    finalize_terminal,
    rebuild_terminal21,
)

__all__ = ["LanguageBuild", "build_languages", "g1a_tables", "BUILDER_VERSION"]

BUILDER_VERSION = "evitea.languages.v1"
CATALOGUE_COLUMNS = ("query_id", "k", "query_seq", "canonical_strand_key", "has_terminal_provenance",
                     "has_internal_provenance", "low_complexity")
PROVENANCE_COLUMNS = ("query_id", "te_id", "family", "k", "start", "region", "source_orientation",
                      "query_seq", "queryable")


def g1a_tables(te_fasta: str | Path, family_map: str | Path) -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    """G1A anchor catalogue and provenance rows (string-typed, historical columns)."""

    catalogue = build_anchor_catalogue(parse_te_consensus(te_fasta), load_te_family_map(family_map))
    rows = [{
        "query_id": q.query_id, "k": str(q.k), "query_seq": q.query_seq,
        "canonical_strand_key": canonical_seq(q.query_seq),
        "has_terminal_provenance": str(int(q.has_terminal)), "has_internal_provenance": str(int(q.has_internal)),
        "low_complexity": str(int(q.low_complexity)),
    } for q in catalogue.queries]
    provenance = [{
        "query_id": s.query_id, "te_id": s.te_id, "family": s.family, "k": str(s.k), "start": str(s.start),
        "region": s.region, "source_orientation": s.orientation, "query_seq": s.query_seq,
        "queryable": str(int(s.queryable)),
    } for s in catalogue.sources]
    return rows, provenance


@dataclass(slots=True)
class LanguageBuild:
    rebuild: RebuildResult
    gap_fill: GapFillResult
    terminal: FinalTerminalResult
    internal: InternalResult

    @property
    def terminal_codebook(self) -> bytes:
        return self.terminal.codebook

    @property
    def internal_only_codebook(self) -> bytes:
        return self.internal.internal_only_codebook

    def hashes(self) -> dict[str, str]:
        return {
            "terminal_final": hashlib.sha256(self.terminal_codebook).hexdigest(),
            "internal_only": hashlib.sha256(self.internal_only_codebook).hexdigest(),
        }

    def audit_tables(self) -> dict[str, bytes]:
        """Every intermediate table, keyed by its historical file name."""

        return {
            "SAFE_TERMINAL21_CANDIDATE_AUDIT.tsv": self.rebuild.candidate_audit,
            "SAFE_TERMINAL21_SOURCE_AUDIT.tsv": self.rebuild.source_audit,
            "REBUILT_SAFE_TERMINAL21_CODEBOOK.tsv": self.rebuild.codebook,
            "REBUILT_SAFE_TERMINAL21_TE_RECORD_SUMMARY.tsv": self.rebuild.te_record_summary,
            "REBUILT_SAFE_TERMINAL21_FAMILY_SUMMARY.tsv": self.rebuild.family_summary,
            "UNDERPOWERED_MIXED_K_SOURCE_AUDIT.tsv": self.gap_fill.source_audit,
            "UNDERPOWERED_TARGET_SUMMARY.tsv": self.gap_fill.target_summary,
            "HYBRID_SAFE_TERMINAL_CODEBOOK.tsv": self.gap_fill.hybrid_codebook,
            "FINAL_SAFE_TERMINAL_CODEBOOK.tsv": self.terminal.codebook,
            "FINAL_SAFE_TERMINAL_RECORD_STATUS.tsv": self.terminal.record_status,
            "FINAL_SAFE_TERMINAL_REPAIR_LOG.tsv": self.terminal.repair_log,
            "SAFE_INTERNAL21_CANDIDATE_AUDIT.tsv": self.internal.candidate_audit,
            "SAFE_INTERNAL21_SOURCE_AUDIT.tsv": self.internal.source_audit,
            "SAFE_INTERNAL21_FULL_CODEBOOK.tsv": self.internal.full_codebook,
            "SAFE_INTERNAL21_INTERNAL_ONLY_CODEBOOK.tsv": self.internal.internal_only_codebook,
            "SAFE_INTERNAL21_TE_RECORD_SUMMARY.tsv": self.internal.te_record_summary,
            "SAFE_INTERNAL21_FAMILY_SUMMARY.tsv": self.internal.family_summary,
        }


def build_languages(
    *,
    te_fasta: str | Path,
    family_map: str | Path,
    reference_fasta: str | Path,
    repeatmasker_bed: str | Path,
    progress: Callable[[str], None] | None = None,
    read_length: int = READ_LENGTH,
) -> LanguageBuild:
    say = progress or (lambda message: None)
    say("languages: G1A anchor catalogue")
    catalogue, provenance = g1a_tables(te_fasta, family_map)
    assets = dict(te_fasta=te_fasta, family_map=family_map, reference_fasta=reference_fasta,
                  repeatmasker_bed=repeatmasker_bed, progress=progress)
    say("languages: rebuild safe terminal k=21")
    rebuild = rebuild_terminal21(catalogue=catalogue, provenance=provenance, **assets)
    say("languages: mixed-k gap fill")
    gap_fill = fill_underpowered(rebuilt_codebook=rebuild.codebook, rebuilt_te_summary=rebuild.te_record_summary,
                                 catalogue=catalogue, provenance=provenance, **assets)
    say("languages: finalize terminal codebook")
    terminal = finalize_terminal(hybrid_codebook=gap_fill.hybrid_codebook, rebuilt_source_audit=rebuild.source_audit,
                                 gapfill_source_audit=gap_fill.source_audit, rebuilt_te_summary=rebuild.te_record_summary)
    say("languages: internal-21 gate")
    internal = build_internal21(
        catalogue=catalogue, provenance=provenance, terminal_codebook=terminal.codebook, read_length=read_length, **assets
    )
    return LanguageBuild(rebuild, gap_fill, terminal, internal)
